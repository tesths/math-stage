<script setup lang="ts">
/**
 * 训练游戏：数的大小比较（相同计数单位比个数）
 */
import { computed, ref } from 'vue'
import { playCorrect, playWin } from '@/lib/sound'
import GameAnswerBar from '@/components/ui/GameAnswerBar.vue'

interface Round {
  a: string
  b: string
  answer: string
}

function randInt(min: number, max: number): number {
  return min + Math.floor(Math.random() * (max - min + 1))
}

const PAIRS = [
  { a: 1000, b: 923 },
  { a: 3.34, b: 3.4 },
  { a: 4.7, b: 4.05 },
  { a: 0.78, b: 0.87 },
  { a: 231, b: 213 },
  { a: 2000, b: 1999 },
]

function makeRound(): Round {
  const p = PAIRS[randInt(0, PAIRS.length - 1)]!
  const a = String(p.a)
  const b = String(p.b)
  return { a, b, answer: p.a > p.b ? '>' : '<' }
}

const roundNo = ref(1)
const rd = ref<Round>(makeRound())
const score = ref(0)
const done = ref(false)
const finished = ref(false)

const answer = computed(() => rd.value.answer)
const options = ['>', '<', '=']

function onAnswered(correct: boolean) {
  done.value = true
  if (correct) score.value++
}
function next() {
  if (roundNo.value >= 5) {
    finished.value = true
    playWin()
    return
  }
  roundNo.value++
  rd.value = makeRound()
  done.value = false
}
function restart() {
  roundNo.value = 1
  score.value = 0
  done.value = false
  finished.value = false
  rd.value = makeRound()
}
</script>

<template>
  <div class="game">
    <div v-if="finished" class="finish">
      <p class="finish-title">⚖️ 数的大小比较过关！</p>
      <p class="finish-sub">5 题答对 {{ score }} 题</p>
      <UButton color="primary" size="lg" @click="restart">再玩一次</UButton>
    </div>

    <template v-else>
      <div class="game-top">
        <span>第 {{ roundNo }}/5 题</span>
        <span>得分 {{ score }}</span>
      </div>

      <div class="expr-card">
        <p class="expr">{{ rd.a }} ○ {{ rd.b }}</p>
        <p class="hint">在 ○ 里填上 &gt;、&lt; 或 =</p>
      </div>

      <GameAnswerBar :options="options" :answer="answer" @answered="onAnswered" />
      <UButton v-if="done" color="primary" size="lg" @click="next">
        {{ roundNo >= 5 ? '查看成绩' : '下一题' }}
      </UButton>
    </template>
  </div>
</template>

