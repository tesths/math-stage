<script setup lang="ts">
/**
 * 训练游戏：有余数的除法（商和余数）
 */
import { computed, ref } from 'vue'
import { playCorrect, playWin } from '@/lib/sound'
import GameAnswerBar from '@/components/ui/GameAnswerBar.vue'

interface Round {
  dividend: number
  divisor: number
  quotient: number
  remainder: number
  answer: string
  options: string[]
}

function randInt(min: number, max: number): number {
  return min + Math.floor(Math.random() * (max - min + 1))
}

function makeRound(): Round {
  const divisor = randInt(2, 9)
  const quotient = randInt(1, 9)
  const remainder = randInt(1, divisor - 1)
  const dividend = divisor * quotient + remainder
  const answer = `${quotient} …… ${remainder}`
  const opts = new Set<string>([answer])
  const variants = [
    `${quotient} …… ${remainder + 1}`,
    `${quotient} …… ${Math.max(0, remainder - 1)}`,
    `${quotient + 1} …… ${remainder}`,
    `${Math.max(1, quotient - 1)} …… ${remainder}`,
    `${quotient} …… ${divisor}`,
  ]
  let i = 0
  while (opts.size < 4 && i < variants.length) {
    const v = variants[i++]!
    if (!opts.has(v)) opts.add(v)
  }
  return { dividend, divisor, quotient, remainder, answer, options: [...opts] }
}

const roundNo = ref(1)
const rd = ref<Round>(makeRound())
const score = ref(0)
const done = ref(false)
const finished = ref(false)

const answer = computed(() => rd.value.answer)
const options = computed(() => rd.value.options)

function onAnswered(correct: boolean) {
  done.value = true
  if (correct) score.value++
}
function next() {
  if (roundNo.value >= 5) {
    finished.value = true
    playWin()
    return
  }
  roundNo.value++
  rd.value = makeRound()
  done.value = false
}
function restart() {
  roundNo.value = 1
  score.value = 0
  done.value = false
  finished.value = false
  rd.value = makeRound()
}
</script>

<template>
  <div class="game">
    <div v-if="finished" class="finish">
      <p class="finish-title">🍯 有余数除法过关！</p>
      <p class="finish-sub">5 题答对 {{ score }} 题</p>
      <UButton color="primary" size="lg" @click="restart">再玩一次</UButton>
    </div>

    <template v-else>
      <div class="game-top">
        <span>第 {{ roundNo }}/5 题</span>
        <span>得分 {{ score }}</span>
      </div>

      <div class="expr-card">
        <p class="expr">{{ rd.dividend }} ÷ {{ rd.divisor }} = ?</p>
        <p class="hint">余数要比除数小（{{ rd.divisor }} 以内）</p>
      </div>

      <GameAnswerBar :options="options" :answer="answer" @answered="onAnswered" />
      <UButton v-if="done" color="primary" size="lg" @click="next">
        {{ roundNo >= 5 ? '查看成绩' : '下一题' }}
      </UButton>
    </template>
  </div>
</template>

