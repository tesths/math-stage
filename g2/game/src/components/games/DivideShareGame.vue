<script setup lang="ts">
/**
 * 训练游戏：平均分（总数 ÷ 份数 = 每份几个）
 */
import { computed, ref } from 'vue'
import { playCorrect, playWin } from '@/lib/sound'
import GameAnswerBar from '@/components/ui/GameAnswerBar.vue'

interface Round {
  total: number
  groups: number
  answer: number
  options: number[]
}

function randInt(min: number, max: number): number {
  return min + Math.floor(Math.random() * (max - min + 1))
}

function makeRound(): Round {
  const groups = randInt(2, 6)
  const each = randInt(2, 6)
  const total = groups * each
  const opts = new Set<number>([each])
  let guard = 0
  while (opts.size < 4 && guard++ < 80) {
    const variant = [each + 1, each - 1, each + 2, total - each, randInt(1, 8), groups, each * 2][randInt(0, 6)]!
    if (variant > 0 && !opts.has(variant)) opts.add(variant)
  }
  return { total, groups, answer: each, options: [...opts].sort((m, n) => m - n) }
}

const roundNo = ref(1)
const rd = ref<Round>(makeRound())
const score = ref(0)
const done = ref(false)
const finished = ref(false)

const answer = computed(() => rd.value.answer)
const options = computed(() => rd.value.options)

function onAnswered(correct: boolean) {
  done.value = true
  if (correct) score.value++
}
function next() {
  if (roundNo.value >= 5) {
    finished.value = true
    playWin()
    return
  }
  roundNo.value++
  rd.value = makeRound()
  done.value = false
}
function restart() {
  roundNo.value = 1
  score.value = 0
  done.value = false
  finished.value = false
  rd.value = makeRound()
}
</script>

<template>
  <div class="game">
    <div v-if="finished" class="finish">
      <p class="finish-title">🍬 平均分过关！</p>
      <p class="finish-sub">5 题答对 {{ score }} 题</p>
      <UButton color="primary" size="lg" @click="restart">再玩一次</UButton>
    </div>

    <template v-else>
      <div class="game-top">
        <span>第 {{ roundNo }}/5 题</span>
        <span>得分 {{ score }}</span>
      </div>

      <div class="expr-card">
        <p class="expr">把 {{ rd.total }} 个平均分成 {{ rd.groups }} 份，每份几个？</p>
        <p class="hint">{{ rd.total }} ÷ {{ rd.groups }} = ?</p>
      </div>

      <GameAnswerBar :options="options" :answer="answer" @answered="onAnswered" />
      <UButton v-if="done" color="primary" size="lg" @click="next">
        {{ roundNo >= 5 ? '查看成绩' : '下一题' }}
      </UButton>
    </template>
  </div>
</template>

