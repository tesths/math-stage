/** 这道例题要建立的概念（带一句易错点） */
export function tipOf(q: Pick<GameQuestion, 'id' | 'type'> & { tip?: string }): string {
  const own = (q.tip ?? '').trim()
  if (own) return own
  const specific = (questionTips[q.id] ?? '').trim()
  if (specific) return specific
  return typeTips[q.type]
}
